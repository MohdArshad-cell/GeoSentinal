    # --- 3. AI PSYOP & INTEGRITY AUDIT (FIXED & ADDED) ---
    def analyze_information_integrity(self, headline, sitrep):
        """Detects sophisticated 2026 propaganda markers."""
        text = (str(headline) + " " + str(sitrep)).lower()
        score = 100
        flags = []

        psyop_markers = {
            "Bot Swarm": ["retweet", "viral", "trending", "unverified footage", "everyone must see"],
            "State Narrative": ["glorious", "liberation", "puppet", "unprovoked attack", "total destruction"],
            "AI Synthesis": ["deepfake", "ai-generated", "synthetic", "generated by ai", "video evidence shows"],
            "Economic Warfare": ["sanctions fail", "currency collapse", "bank run imminent"]
        }

        for category, keywords in psyop_markers.items():
            matches = [k for k in keywords if k in text]
            if matches:
                deduction = 20 if category != "AI Synthesis" else 35
                score -= deduction
                flags.append(f"{category}")

        status = "Verified Organic" if score >= 85 else ("Disputed" if score >= 60 else "High-Intensity PsyOp")
        return {"integrity_score": max(0, score), "narrative_status": status, "flags": flags}

