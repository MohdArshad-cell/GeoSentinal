    # --- 5. SOCIAL PANIC CALCULATOR ---
    def get_public_panic_index(self, gpti_score):
        """Determines the 'Civilian Fear Index' based on Sigmoid curve logic."""
        # P(g) = 100 / (1 + e^-10(g - 0.6))
        k = 10 
        x0 = 0.6 
        panic = 100 / (1 + math.exp(-k * (gpti_score - x0)))
        
        terms_pool = ["Emergency Kit", "Nearest Bunker", "Flight Status", "Bank Withdrawal", "Fuel Prices", "Draft Age"]
        trending = random.sample(terms_pool, 2) if gpti_score > 0.4 else ["Market Stability", "Weather Update"]
        
        return round(panic, 2), trending

