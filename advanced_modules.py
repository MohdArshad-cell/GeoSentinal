    def _sanitize_zone(self, zone):
        """Cleans theater names for high-speed logic matching."""
        if not zone: return "GLOBAL"
        return zone.split(' ')[0].split('-')[0].upper()

    # --- 1. MULTI-DOMAIN THREAT MATRIX ---
    def generate_threat_matrix(self, gpti_score, conflict_zone):
        """Calculates 5-axis threat levels using a weighted intensity formula."""
        zone = self._sanitize_zone(conflict_zone)
        base = gpti_score * 100
        
        matrix = {
            "Kinetic (Military)": min(100, base * 1.05),
            "Narrative (PsyOps)": min(100, base * 1.15),
            "Economic Linkage": min(100, base * 0.85),
            "Cyber & Grid": min(100, base * 1.10),
            "Nuclear Posture": min(100, base * 0.70 if gpti_score < 0.8 else base * 1.3)
        }

        # Theater Overrides
        if zone == "RUSSIA" or zone == "UKRAINE":
            matrix["Economic Linkage"] += 15
            matrix["Cyber & Grid"] += 10
        elif zone == "INDIA" or zone == "PAKISTAN":
            matrix["Narrative (PsyOps)"] += 20
        elif zone == "IRAN" or zone == "ISRAEL":
            matrix["Cyber & Grid"] += 25
            matrix["Nuclear Posture"] += 15

        return {k: round(min(100, v), 2) for k, v in matrix.items()}

